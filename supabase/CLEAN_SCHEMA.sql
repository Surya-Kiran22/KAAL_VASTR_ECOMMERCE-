-- 10.1 Promote an existing account to admin (first-admin bootstrap).
create or replace function public.promote_to_admin(target_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles p
     set role = 'admin'
    from auth.users u
   where u.id = p.id
     and lower(u.email) = lower(target_email);

  if not found then
    raise exception 'No account found for %. Sign the user up first.', target_email;
  end if;

  update auth.users u
     set raw_user_meta_data = coalesce(u.raw_user_meta_data, '{}'::jsonb)
                             || jsonb_build_object('role', 'admin')
   where lower(u.email) = lower(target_email);
end;
$$;

-- 10.2 Set any account's role. Callable by signed-in admins only.
create or replace function public.set_user_role(target_email text, new_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can change account roles';
  end if;

  if new_role not in ('customer', 'staff', 'admin') then
    raise exception 'Invalid role: % (expected customer, staff or admin)', new_role;
  end if;

  update public.profiles p
     set role = new_role
    from auth.users u
   where u.id = p.id
     and lower(u.email) = lower(target_email);

  if not found then
    raise exception 'No account found for %', target_email;
  end if;

  update auth.users u
     set raw_user_meta_data = coalesce(u.raw_user_meta_data, '{}'::jsonb)
                             || jsonb_build_object('role', new_role)
   where lower(u.email) = lower(target_email);
end;
$$;

-- 10.3 Enable / disable an account without deleting its history.
create or replace function public.set_user_active(target_email text, active boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can change account status';
  end if;

  update public.profiles p
     set is_active = active
    from auth.users u
   where u.id = p.id
     and lower(u.email) = lower(target_email);

  if not found then
    raise exception 'No account found for %', target_email;
  end if;
end;
$$;

revoke all on function public.set_user_role(text, text)   from public, anon;
revoke all on function public.set_user_active(text, boolean) from public, anon;
grant execute on function public.set_user_role(text, text)      to authenticated;
grant execute on function public.set_user_active(text, boolean) to authenticated;

-- Repair any account whose metadata cache drifted from profiles.role.
update auth.users u
   set raw_user_meta_data = coalesce(u.raw_user_meta_data, '{}'::jsonb)
                           || jsonb_build_object('role', p.role)
  from public.profiles p
 where p.id = u.id
   and (u.raw_user_meta_data ->> 'role') is distinct from p.role;


