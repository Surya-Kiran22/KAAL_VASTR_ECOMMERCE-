-- Row-level safety net: even if a wider UPDATE grant is ever restored, an
-- admin can never move a dispatch status.
create or replace function public.orders_block_admin_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status and not public.is_staff_only() then
    raise exception 'Only staff accounts can update the dispatch status';
  end if;

  if new.status is distinct from old.status then
    new.status_updated_by := auth.uid();
    new.status_updated_at := now();
  end if;

  return new;
end;
$$;

drop trigger if exists trg_orders_staff_only_status on public.orders;
create trigger trg_orders_staff_only_status
  before update on public.orders
  for each row execute function public.orders_block_admin_status_change();

-- Append the audit row whenever the status actually changes.
create or replace function public.log_order_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status then
    insert into public.order_status_history
      (order_id, from_status, to_status, changed_by, note)
    values
      (new.id, old.status, new.status, auth.uid(), new.dispatch_note);
  end if;
  return new;
end;
$$;

drop trigger if exists trg_orders_log_status on public.orders;
create trigger trg_orders_log_status
  after update on public.orders
  for each row execute function public.log_order_status_change();

