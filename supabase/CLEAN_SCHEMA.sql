-- 2.4 variant_stock format
comment on column public.products.variant_stock is
  'Per colour+size stock, keyed "Color|Size" with a non-negative integer value, '
  'e.g. {"Obsidian Black|S":4,"Obsidian Black|M":0,"Charcoal Grey|XL":3}. '
  'NULL or {} means the product uses the flat stock column only. '
  'A colour+size absent from the map is treated as 0 (out of stock). '
  'Maintained by the admin product form; validated by '
  'products_variant_stock_is_valid() and totalled by products_sync_total_stock().';

-- 2.4a Reject malformed variant payloads before they reach the table.
--      Trigger function: volatility is intentionally left at the default
--      because it raises exceptions rather than computing a value.
create or replace function public.products_variant_stock_is_valid()
returns trigger
language plpgsql
as $$
declare
  entry jsonb;
begin
  if new.variant_stock is null or new.variant_stock = '{}'::jsonb then
    return new;
  end if;

  if jsonb_typeof(new.variant_stock) <> 'object' then
    raise exception 'variant_stock must be a JSON object keyed "Color|Size"';
  end if;

  for entry in select * from jsonb_each(new.variant_stock) loop
    if entry.key !~ '\|' then
      raise exception 'variant_stock key "%" must be in the form "Color|Size"', entry.key;
    end if;

    if jsonb_typeof(entry.value) <> 'number'
       or (entry.value #>> '{}')::numeric < 0
       or (entry.value #>> '{}')::numeric <> trunc((entry.value #>> '{}')::numeric) then
      raise exception 'variant_stock["%"] must be a non-negative whole number', entry.key;
    end if;
  end loop;

  return new;
end;
$$;

drop trigger if exists trg_products_variant_stock_valid on public.products;
create trigger trg_products_variant_stock_valid
  before insert or update of variant_stock on public.products
  for each row execute function public.products_variant_stock_is_valid();

-- 2.5 Keep the flat stock total and availability in step with the variants, so
--     list views and sales analytics stay correct without extra joins.
create or replace function public.products_sync_total_stock()
returns trigger
language plpgsql
as $$
declare
  total integer;
begin
  if new.variant_stock is not null
     and jsonb_typeof(new.variant_stock) = 'object'
     and new.variant_stock <> '{}'::jsonb then

    select coalesce(sum(value::text::numeric), 0)::integer
      into total
      from jsonb_each_text(new.variant_stock);

    new.stock := total;

    if total = 0 then
      new.is_available := false;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_products_sync_total_stock on public.products;
create trigger trg_products_sync_total_stock
  before insert or update of variant_stock on public.products
  for each row execute function public.products_sync_total_stock();


